const assert = require('node:assert/strict');
const fs = require('node:fs');
const P = require('../tools/project_probe_protocol.js');
const man = JSON.parse(fs.readFileSync('firmware/a0177/manifest.json'));
const html = fs.readFileSync('tools/project_probe.html','utf8');
assert(html.includes(`const SLOT = ${man.report.projectprobe.slot};`));
const req = P.request(0x2004f340,64,7);
assert.equal(req.length,232); assert.equal(req[4],2); assert.equal(req[231],247);
assert.deepEqual([...req.slice(6,14)], [2,0,0,4,15,3,4,0]);
assert.throws(() => P.request(0x08010000,1,0));
assert.throws(() => P.request(0x20000000,65,0));
const reply = Uint8Array.from([240,125,67,84,66,7,...Array(8).fill(0),10,11,247]);
assert.deepEqual([...P.reply(reply,7,1)],[171]);
assert.equal(P.reply(reply,8,1),null);
assert.throws(() => P.reply(reply,7,2));
const data = new Uint8Array(1056), view = new DataView(data.buffer);
view.setUint32(0,0x31505052,true); view.setUint32(4,2,true);
const events=[[1,0xfffffffe,1,17,0x08030003,0,169092,0],[2,4,2,17,0x08030003,0,169092,0]];
events.forEach((e,i) => e.forEach((v,j)=>view.setUint32(32+i*32+j*4,v,true)));
const result=P.decode(data);
assert.equal(result.events.length,2); assert.equal(result.reads[0].elapsedMs,6);
assert.equal(result.reads[0].packContext,3);
assert.equal(result.reads[0].bytes,169092);
assert.throws(() => P.decode(new Uint8Array(1056)));
console.log('ALL PASS: A0177 manifest address, RAM-only requests, reply validation, event decode and timer wrap');
